"""Regenerate src/tables_gen.rs from the package's own data files plus the
build interpreter's unicodedata.

Zero-skew rule: every validation table the Rust kernel uses comes from the
same sources as the pure-Python implementation (idnadata/uts46data for
IDNA/UTS-46; local unicodedata for bidi/category/combining/name, matching
the oracle interpreter exactly). Rerun on every upstream bump or
interpreter change; the generated header records both versions.

Usage: <lane-venv-python> tools/gen_tables.py  (run from repo root)
"""

import array
import datetime
import sys
import unicodedata

sys.path.insert(0, "idna")
import idnadata
import uts46data

OUT = "src/tables_gen.rs"


def decode_ranges(enc):
    out = []
    for r in enc:
        out.append((r >> 32, r & 0xFFFFFFFF))
    return out


def rust_str(s):
    out = []
    for ch in s:
        o = ord(ch)
        if ch == '"':
            out.append('\\"')
        elif ch == '\\':
            out.append('\\\\')
        elif o < 0x20 or o == 0x7F:
            out.append(f"\\u{{{o:X}}}")
        else:
            out.append(ch)
    return '"' + "".join(out) + '"'

def emit_u32_ranges(name, enc, fh):
    rngs = decode_ranges(enc)
    fh.write(f"pub static {name}: &[(u32, u32)] = &[\n")
    for s, e in rngs:
        fh.write(f"    ({s}, {e}),\n")
    fh.write("];\n")
    return len(rngs)


def main():
    py_version = ".".join(map(str, sys.version_info[:3]))
    with open(OUT, "w") as fh:
        fh.write(f"//! Generated by tools/gen_tables.py on {datetime.date.today()}.\n")
        fh.write(f"//! idna={uts46data.__version__} tables; unicodedata Unicode "
                 f"{unicodedata.unidata_version} (CPython {py_version}).\n")
        fh.write("//! DO NOT EDIT — regenerate, do not hand-patch.\n\n")
        # UTS-46: parallel starts/statuses + mapped-only (cp -> replacement).
        starts = list(uts46data.uts46_starts)
        assert starts == sorted(starts)
        statuses = bytes(uts46data.uts46_statuses)
        reps = uts46data.uts46_replacements
        assert len(starts) == len(statuses) == len(reps)
        nmap = sum(1 for b, r in zip(statuses, reps) if b == 77 and r is not None)
        fh.write(f"pub static UTS46_STARTS: &[u32] = &[\n")
        for i in range(0, len(starts), 8):
            fh.write("    " + ", ".join(str(x) for x in starts[i:i + 8]) + ",\n")
        fh.write("];\n")
        fh.write(f"pub static UTS46_STATUS: &[u8] = b\"")
        fh.write("".join(f"\\x{b:02x}" for b in statuses))
        fh.write("\";\n")
        fh.write("pub static UTS46_MAP: &[(u32, &str)] = &[\n")
        for cp, b, r in zip(starts, statuses, reps):
            if b == 77 and r is not None:  # M only; D-row reps are ignored
                fh.write(f"    ({cp}, {rust_str(r)}),\n")
        fh.write("];\n")
        print(f"uts46: {len(starts)} rows, {nmap} mapped")

        # IDNA classes + scripts + joining types (intranges-encoded tuples).
        total = 0
        for name in ("PVALID", "CONTEXTJ", "CONTEXTO"):
            total += emit_u32_ranges(f"CLASS_{name}",
                                     idnadata.codepoint_classes[name], fh)
        for name, enc in idnadata.scripts.items():
            total += emit_u32_ranges(f"SCRIPT_{name.upper()}", enc, fh)
        for name, enc in idnadata.joining_types.items():
            total += emit_u32_ranges(f"JOINING_{name}", enc, fh)
        print(f"idna classes/scripts/joining ranges: {total}")

        # unicodedata-derived per-codepoint properties, run-compressed.
        # Key per codepoint: (bidi_id, combining, is_M, has_name).
        bidi_names = []
        runs = []
        cur = None
        N = 0x110000
        for cp in range(N):
            ch = chr(cp)
            bidi = unicodedata.bidirectional(ch)
            if bidi not in bidi_names:
                bidi_names.append(bidi)
            comb = unicodedata.combining(ch)
            cat = unicodedata.category(ch)
            is_m = 1 if cat in ("Mn", "Mc", "Me") else 0
            # name() only matters when combining == 0 (see _combining_class);
            # still computed exactly for every codepoint.
            has_name = 0 if unicodedata.name(ch, None) is None else 1
            key = (bidi_names.index(bidi), comb, is_m, has_name)
            if cur is None or cur[1] != key:
                if cur is not None:
                    runs.append(cur)
                cur = [cp, key, cp]
            else:
                cur[2] = cp
        runs.append(cur)
        fh.write("pub static BIDI_NAMES: &[&str] = &[")
        fh.write(", ".join(rust_str(b) for b in bidi_names))
        fh.write("];\n")
        fh.write("/// (start, end_exclusive, bidi_id, combining, flags(is_M<<1|has_name))\n")
        fh.write("pub static UCD_RUNS: &[(u32, u32, u8, u8, u8)] = &[\n")
        for start, key, end in runs:
            fh.write(f"    ({start}, {end + 1}, {key[0]}, {key[1]}, {(key[2] << 1) | key[3]}),\n")
        fh.write("];\n")
        print(f"ucd: {len(bidi_names)} bidi classes, {len(runs)} runs")


if __name__ == "__main__":
    main()
